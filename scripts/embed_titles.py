#!/usr/bin/env python3
"""Turn every title into a list of 384 numbers with all-MiniLM-L6-v2, and check the shipped ones.

The vectors used in the paper are shipped in data/embeddings/<name>__all-minilm-l6-v2.npy
(float32, one row per title, in the order of data/titles/<name>.parquet), so every result
reproduces exactly. This script regenerates them from the titles with the pinned model revision
(title text alone) and compares them with the shipped vectors. Regenerated vectors match to
within about 2e-7 (floating-point rounding). The shipped vectors are used because that rounding
can tip a handful of comparisons that sit exactly at a cutoff (e.g., one title of 12,199 changes
whether its neighborhood is presentation-heavy).

By default the regenerated vectors go to cache/embeddings and the shipped ones are untouched;
--write replaces the shipped vectors with regenerated ones.

Title tables
------------
* conference, apba, sqab: presentation titles (ABAI, APBA, SQAB)
* journal, specialty: article titles (eight general and six specialty behavior-analysis journals;
  The Behavior Analyst and its successor, Perspectives on Behavior Science, count as one)
* conference_fit, journal_fit: the ABAI and general-journal titles the subject-area groups are
  fit on (presented_published.groups)

Output: results/embedding_check.md
Run:    python scripts/embed_titles.py   (downloads the model on first use)
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd
from sentence_transformers import SentenceTransformer

from presented_published.groups import EMB, SLUG, TITLES

MODEL = "sentence-transformers/all-MiniLM-L6-v2"
REVISION = "1110a243fdf4706b3f48f1d95db1a4f5529b4d41"
NAMES = ("conference", "apba", "sqab", "journal", "specialty", "conference_fit", "journal_fit")
CHECK_DIR = Path("cache/embeddings")
REPORT = Path("results/embedding_check.md")
TOLERANCE = 1e-5


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--write", action="store_true",
                    help="replace the shipped vectors in data/embeddings with regenerated ones")
    args = ap.parse_args()
    out_dir = EMB if args.write else CHECK_DIR
    out_dir.mkdir(parents=True, exist_ok=True)
    model = SentenceTransformer(MODEL, revision=REVISION)
    rows = []
    for name in NAMES:
        titles = pd.read_parquet(TITLES / f"{name}.parquet")["title"]
        texts = [str(t or "") for t in titles]
        V = np.asarray(model.encode(texts, batch_size=512, convert_to_numpy=True),
                       dtype=np.float32)
        shipped = EMB / f"{name}__{SLUG}.npy"
        diff = float(np.abs(V - np.load(shipped)).max()) if shipped.exists() else float("nan")
        np.save(out_dir / f"{name}__{SLUG}.npy", V)
        rows.append((name, len(texts), diff))
        print(f"{name}: {len(texts):,} titles; max |regenerated - shipped| = {diff:.1e}",
              flush=True)
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    lines = "\n".join(f"| {n} | {k:,} | {d:.1e} |" for n, k, d in rows)
    REPORT.write_text(f"""# Embedding check

Generated by `scripts/embed_titles.py`. Model {MODEL}, revision {REVISION[:8]}, title text only.

| Title table | Titles | Largest difference, regenerated vs. shipped |
|---|---:|---:|
{lines}
""", encoding="utf-8")
    worst = max(d for _, _, d in rows)
    if not args.write and not worst <= TOLERANCE:
        raise SystemExit(f"regenerated vectors differ from the shipped ones by {worst:.1e}")


if __name__ == "__main__":
    main()
