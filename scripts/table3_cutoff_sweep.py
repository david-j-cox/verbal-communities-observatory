#!/usr/bin/env python3
# ruff: noqa: E501  (report template)
"""Sensitivity of the flags to the two cutoffs (Table 3).

Research question
-----------------
How do the flag rates change with the number of nearest titles that define a neighbourhood
(K = 50 to 100) and with the definition of few closely related articles (none, fewer than 5,
fewer than 10)? And do the same subject-area groups lead under every definition?

Independent variables: K in KS; N in NS (closely related line fixed at the 99th percentile of
all-pair similarity, as in the primary analysis).
Dependent variables: titles, presentations, and articles flagged (count and percent); the groups
with at least MIN_TITLES titles ranked by their proportion of titles flagged.

Data: scripts/screen.records() (all 2016-2026 titles); groups from
scripts/subject_groups.groupings() (k = 200, seed 0, synonym merge); labels from
data/labels/group_labels.csv.

Outputs
-------
* results/table3_cutoff_sweep.csv: one row per (K, N).
* results/table3_cutoff_sweep.md: the table and the top groups per definition.
Run:  python scripts/table3_cutoff_sweep.py   (after scripts/subject_groups.py)
"""
from __future__ import annotations

from datetime import date
from pathlib import Path

import numpy as np
import pandas as pd

from presented_published.neighborhood import (
    article_count,
    nearest,
    pair_quantile,
    similarity,
    skew_scores,
)
from screen import K0, N0, NS, Q, records
from subject_groups import MIN_TITLES, groupings

KS = (50, 60, 70, 75, 80, 90, 100)
TOP = 5
SCREEN = Path("results/neighborhood_screen.parquet")
OUT = Path("results/table3_cutoff_sweep.csv")
REPORT = Path("results/table3_cutoff_sweep.md")


def main() -> None:
    V, rec = records()
    pres = rec["presented"].to_numpy()
    S = similarity(V)
    count = article_count(S, pres, pair_quantile(V, Q))
    g0 = groupings(V)["k200_s0"]
    names = pd.read_csv("data/labels/group_labels.csv").set_index("topic")["label"]
    size = pd.Series(g0).value_counts()
    big = size.index[size >= MIN_TITLES]
    arch = pd.read_parquet(SCREEN)

    rows, tops = [], {}
    for k in KS:
        # Each K gets its own nearest() call, as in the screen, so ties at rank K resolve alike.
        sk = skew_scores(nearest(S, k), pres, k)
        for n in NS:
            f = sk["skewed"] & (count < n)
            col = f"flag_k{k}_lt{n}"
            if col in arch and not np.array_equal(arch[col].to_numpy(), f):
                raise SystemExit(f"{col} differs from the archived screen")
            share = pd.Series(f.astype(float)).groupby(g0).mean().loc[big]
            top = share.sort_values(ascending=False).head(TOP)
            tops[(k, n)] = [names[g] for g in top.index]
            rows.append({"k": k, "n": n, "titles": int(f.sum()), "titles_pct": f.mean() * 100,
                         "pres": int(f[pres].sum()), "pres_pct": f[pres].mean() * 100,
                         "pub": int(f[~pres].sum()), "pub_pct": f[~pres].mean() * 100,
                         "top_groups": " | ".join(tops[(k, n)])})
        print(f"K = {k} done", flush=True)
    tab = pd.DataFrame(rows)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    tab.to_csv(OUT, index=False)

    ref = tops[(K0, N0)][:3]
    lab = {1: "none", 5: "fewer than 5", 10: "fewer than 10"}
    lines = "\n".join(
        f"| {r.k} | {lab[r.n]} | {r.titles:,} ({r.titles_pct:.1f}%) | {r.pres:,} ({r.pres_pct:.1f}%) "
        f"| {r.pub:,} ({r.pub_pct:.1f}%) | {sum(t in r.top_groups.split(' | ') for t in ref)} of 3 |"
        for r in tab.itertuples())
    REPORT.write_text(f"""# Sensitivity to K and to the closely related cut

Generated by `scripts/table3_cutoff_sweep.py` on {date.today().isoformat()}. {len(rec):,}
titles; closely related line fixed at the 99th percentile of all-pair similarity. Groups with at
least {MIN_TITLES} titles ranked by their proportion of titles flagged. Last column: how many of
the three leading groups under the primary definition (K = {K0}, fewer than {N0}) are among the
top {TOP} under each definition. Primary top three: {"; ".join(ref)}.

| K | Closely related articles | Titles flagged | Presentations flagged | Articles flagged | Primary top three in top {TOP} |
|---:|---|---|---|---|---:|
{lines}

## Top {TOP} groups per definition

""" + "\n".join(f"- K = {k}, {lab[n]}: {'; '.join(v)}" for (k, n), v in tops.items()) + "\n",
        encoding="utf-8")
    print(REPORT.read_text())


if __name__ == "__main__":
    main()
